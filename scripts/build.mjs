import { readFile, mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const { name } = JSON.parse(await read('package.json'));
const dictionaries = {};
const browserBundle = {
  bundle: true, platform: 'browser', target: 'es2022', minify: true, legalComments: 'eof', metafile: true,
};

function reportBundle(result, file) {
  const output = Object.values(result.metafile.outputs).find(output => output.entryPoint);
  if (!output || output.imports.length) throw new Error(`${file} must be self-contained`);
  console.log(`Built self-contained ${file} (${output.bytes} bytes)`);
}

for (const lang of ['en', 'zh']) {
  const { meta, ...ui } = JSON.parse(await read(`locale/${lang}.json`));
  dictionaries[lang] = ui;
}
await build({
  ...browserBundle,
  stdin: {
    contents: `import * as core from './theme/palette.js';
import { createPlugin } from './client-main.js';
import { createAppearanceController } from './theme/appearance.js';
window.__ModuleLoader__.load({
  id: ${JSON.stringify(name)},
  factory(require) {
    return createPlugin(require('react'), core, ${JSON.stringify(dictionaries)}, createAppearanceController);
  },
});`,
    resolveDir: fileURLToPath(new URL('src/client/', root)), sourcefile: 'client-entry.js', loader: 'js',
  },
  outfile: fileURLToPath(new URL('dist/client.js', root)),
  format: 'iife',
  banner: { js: '// Generated by npm run build. Edit the plugin source files instead.' },
}).then(result => reportBundle(result, 'dist/client.js'));
await build({
  ...browserBundle,
  entryPoints: [fileURLToPath(new URL('src/client/wallpaper/parallax-sharp-renderer.js', root))],
  outfile: fileURLToPath(new URL('dist/sharp-renderer.js', root)),
  format: 'esm',
}).then(result => reportBundle(result, 'dist/sharp-renderer.js'));
await mkdir(new URL('third-party/', root), { recursive: true });
await copyFile(new URL('node_modules/@material/material-color-utilities/LICENSE', root), new URL('third-party/material-color-utilities-LICENSE.txt', root));
await copyFile(new URL('node_modules/three/LICENSE', root), new URL('third-party/three-LICENSE.txt', root));
await copyFile(new URL('node_modules/@sparkjsdev/spark/LICENSE', root), new URL('third-party/spark-LICENSE.txt', root));
