import { readFile, mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const dictionaries = {};
for (const lang of ['en', 'zh']) {
  const { meta, ...ui } = JSON.parse(await read(`locale/${lang}.json`));
  dictionaries[lang] = ui;
}
await build({
  stdin: {
    contents: `import * as core from './palette.js';
import { createPlugin } from './client-main.js';
import { createAppearanceController } from './appearance.js';
window.__ModuleLoader__.load({
  id: '@local/dsh-bing-daily-theme',
  factory(require) {
    return createPlugin(require('react'), core, ${JSON.stringify(dictionaries)}, createAppearanceController);
  },
});`,
    resolveDir: fileURLToPath(root), sourcefile: 'client-entry.js', loader: 'js',
  },
  outfile: fileURLToPath(new URL('client.js', root)),
  bundle: true, format: 'iife', platform: 'browser', target: 'es2022',
  minify: true, legalComments: 'eof',
  banner: { js: '// Generated by npm run build. Edit palette.js / client-main.js / appearance.js / boot-theme.js / compatibility.js / palette-preview.js instead.' },
  metafile: true,
}).then(result => {
  const output = Object.values(result.metafile.outputs).find(output => output.entryPoint);
  if (!output || output.imports.length) throw new Error('Browser artifact must be self-contained');
  console.log(`Built self-contained client.js (${output.bytes} bytes)`);
});
await mkdir(new URL('third-party/', root), { recursive: true });
await copyFile(new URL('node_modules/@material/material-color-utilities/LICENSE', root), new URL('third-party/material-color-utilities-LICENSE.txt', root));
